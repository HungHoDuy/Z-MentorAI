    core_skills = list(dict.fromkeys(skill for group in essential_skill_groups for skill in group))
    supporting_skills = [skill for skill in supporting if skill not in core_skills]
    return {
        "label": label,
        "aliases": aliases,
        "core_skills": core_skills,
        "essential_skill_groups": essential_skill_groups,
        "supporting_skills": supporting_skills,
        "education_keywords": education,
        "riasec": riasec,
        "level": level,
        "scorable": True,
    }


